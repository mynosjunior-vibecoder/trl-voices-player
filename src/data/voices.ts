// Helper to generate a realistic waveform sequence with natural speech dynamics
const generatePeaks = (seed: number, count = 60): number[] => {
  const peaks: number[] = [];
  for (let i = 0; i < count; i++) {
    // Combine multiple sine waves and noise for natural speech-like envelopes
    const phraseEnvelope = Math.sin((i / count) * Math.PI);
    const syllablePulse = Math.abs(Math.sin(i * 0.45 + seed));
    const microVariation = ((Math.sin(i * 1.7 + seed * 2) + 1) / 2) * 0.35;
    const peak = Math.max(0.12, Math.min(0.98, phraseEnvelope * syllablePulse * 0.8 + microVariation));
    peaks.push(Number(peak.toFixed(2)));
  }
  return peaks;
};

